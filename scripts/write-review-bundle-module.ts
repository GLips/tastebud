/**
 * Writes `apps/review/dist/review-bundle.ts`, the module `@taste/review/bundle` names: every built client file
 * imported `with { type: "file" }` (a path in dist/ from source, an embedded `$bunfs` file in a compiled binary)
 * and the server entry's `fetch`. Runs after `vite build`; apps/review/review-bundle.d.ts declares its shape.
 */
import { fileURLToPath } from "node:url";

import { Glob } from "bun";

const distDir = fileURLToPath(new URL("../apps/review/dist/", import.meta.url));
const clientFiles = [...new Glob("**/*").scanSync(`${distDir}client`)].sort();

// `./client/...`: a specifier without the leading `./` would resolve as a package name.
const imports = clientFiles.map(
  (file, index) =>
    `import clientFile${String(index)} from ${JSON.stringify(`./client/${file}`)} with { type: "file" };`,
);
const entries = clientFiles.map((file, index) => `  ${JSON.stringify(`/${file}`)}: clientFile${String(index)},`);

const moduleText = `// Generated by scripts/write-review-bundle-module.ts after \`vite build\`. Do not edit.
import reviewServerEntry from "./server/server.js";
${imports.join("\n")}

export const REVIEW_CLIENT_ASSETS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};

export const fetchReviewServerEntry = (request: Request): Promise<Response> => reviewServerEntry.fetch(request);
`;

await Bun.write(`${distDir}review-bundle.ts`, moduleText);
process.stdout.write(`review bundle: ${String(clientFiles.length)} client files -> ${distDir}review-bundle.ts\n`);
